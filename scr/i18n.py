    LANG = "en"

    @classmethod
    def init(cls, force_lang: str | None = None):
        """Detect and set system language according to requirements:
        pl / pl-* -> pl
        de / de-* -> de
        fr / fr-* -> fr
        everything else -> en
        """
        if force_lang:
            target = force_lang.lower().split("_")[0].split("-")[0]
            cls.LANG = target if target in cls._TRANSLATIONS else "en"
            return cls.LANG

        env_lang = os.getenv("COMPARATOR_LOCALE") or os.getenv("COMPARATOR_LANG")
        if env_lang:
            target = env_lang.lower().split("_")[0].split("-")[0]
            cls.LANG = target if target in cls._TRANSLATIONS else "en"
            return cls.LANG

        try:
            from PySide6.QtCore import QLocale
            loc = QLocale.system()
            lang_code = loc.name().lower().split("_")[0].split("-")[0]
            if lang_code in cls._TRANSLATIONS:
                cls.LANG = lang_code
            else:
                # Also check enum
                lang_enum = loc.language()
                if lang_enum == QLocale.Language.Polish:
                    cls.LANG = "pl"
                elif lang_enum == QLocale.Language.German:
                    cls.LANG = "de"
                elif lang_enum == QLocale.Language.French:
                    cls.LANG = "fr"
                else:
                    cls.LANG = "en"
        except Exception:
            cls.LANG = "en"

        return cls.LANG

    @classmethod
    def tr(cls, key: str, **kwargs) -> str:
        translations = cls._TRANSLATIONS.get(cls.LANG, cls._TRANSLATIONS["en"])
        text = translations.get(key)
        if text is None:
            text = cls._TRANSLATIONS["en"].get(key, key)
        if isinstance(text, str) and kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text

    @classmethod
    def current_lang(cls) -> str:
        return cls.LANG

